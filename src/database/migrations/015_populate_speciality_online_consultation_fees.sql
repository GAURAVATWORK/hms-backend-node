    WHEN 'CARDIOLOGY' THEN 300.00
    WHEN 'NEUROLOGY' THEN 300.00
    WHEN 'ORTHOPAEDICS' THEN 150.00
    WHEN 'GASTROENTEROLOGY' THEN 230.00
    WHEN 'GENERAL_MEDICINE' THEN 150.00
    WHEN 'PULMONOLOGY' THEN 150.00
    WHEN 'PSYCHIATRY' THEN 230.00
    WHEN 'ENT' THEN 175.00
    WHEN 'NEPHROLOGY' THEN 300.00
    WHEN 'GYNECOLOGY' THEN 150.00
    WHEN 'PEDIATRICS' THEN 175.00
    WHEN 'DERMATOLOGY' THEN 300.00
    WHEN 'OPHTHALMOLOGY' THEN 230.00
    WHEN 'DENTAL' THEN 150.00
    WHEN 'ONCOLOGY' THEN 300.00
    WHEN 'ENDOCRINOLOGY' THEN 300.00
    WHEN 'UROLOGY' THEN 300.00
    WHEN 'RHEUMATOLOGY' THEN 300.00
    WHEN 'ANDROLOGY_SEXUAL_HEALTH' THEN 150.00
    WHEN 'GENERAL_SURGERY' THEN 150.00
    WHEN 'VASCULAR_SURGERY' THEN 300.00
